package kr.auto.titration.mobile.data

import java.util.Locale

/** CSV row values produced locally on the phone. */
data class CsvFeatureRow(
    val schemaVersion: String,
    val experimentId: String,
    val frameId: Long,
    val timeS: Double,
    val visibleTimeS: Double?,
    val thermalTimeS: Double?,
    val syncOffsetMs: Double?,
    val syncQuality: String,
    val injectedVolumeMl: Double,
    val distanceToEquivalenceMl: Double?,
    val pumpState: String,
    val pumpRateMlPerS: Double,
    val pumpStepCount: Long? = null,
    val pumpConfirmedStepCount: Long? = null,
    val pumpFirmwareVolumeMl: Double? = null,
    val pumpLastStatusLine: String = "",
    val visibleRMean: Double?,
    val visibleGMean: Double?,
    val visibleBMean: Double?,
    val visibleHMean: Double?,
    val visibleSMean: Double?,
    val visibleVMean: Double?,
    val visibleHsvDelta: Double?,
    val visibleColorDelta: Double?,
    val roiShape: String = "rectangle",
    val visibleRoiShape: String = "rectangle",
    val thermalRoiShape: String = "rectangle",
    val visibleMaskSource: String = "",
    val thermalMaskSource: String = "",
    val visibleMaskAreaPx: Int? = null,
    val visibleMaskConfidence: Double? = null,
    val visibleMaskBbox: String = "",
    val visibleMaskComponentCount: Int? = null,
    val visibleMaskStability: String = "",
    val thermalMaskAreaPx: Int? = null,
    val thermalMaskConfidence: Double? = null,
    val thermalMaskBbox: String = "",
    val thermalMaskComponentCount: Int? = null,
    val thermalMaskStability: String = "",
    val maskBbox: String = "",
    val maskConfidence: Double? = null,
    val maskComponentCount: Int? = null,
    val maskStability: String = "",
    val autoRoiWorkerEnabled: Boolean = true,
    val autoRoiResultStatus: String = "",
    val autoRoiResultReason: String = "",
    val autoRoiDroppedPending: Int = 0,
    val thermalCalibrated: Boolean,
    val thermalConversionModel: String,
    val thermalMatrixShape: String = "",
    val thermalRawRoiAvg: Double? = null,
    val thermalRawRoiMin: Double? = null,
    val thermalRawRoiMax: Double? = null,
    val thermalRawMean: Double? = null,
    val thermalRawMin: Double? = null,
    val thermalRawMax: Double? = null,
    val thermalRawRoiStd: Double? = null,
    val thermalRawRoiDelta: Double? = null,
    val thermalRawRoiP50: Double? = null,
    val thermalRawRoiIqr: Double? = null,
    val thermalRawStd: Double? = null,
    val csvSessionId: String = "",
    val csvRowIndex: Int? = null,
    val csvRecordingStartedEpochS: Double? = null,
    val csvRecordingElapsedS: Double? = null,
    val pumpElapsedS: Double? = null,
    val theoreticalEquivalenceTimeS: Double? = null,
    val timeToEquivalenceS: Double? = null,
    val equivalenceWindowMl: Double? = null,
    val equivalenceWindowLabel: String = "",
    val sampleConcentrationFromInjectedM: Double? = null,
    val sampleConcentrationErrorPercent: Double? = null,
    val pendingAutoCandidateRequests: Int = 0,
    val pendingAutoCandidateTarget: String = "",
    val warnings: String = "",
) {
    fun toCsvMap(config: ExperimentConfig): Map<String, String> {
        return mapOf(
            "schema_version" to schemaVersion,
            "experiment_id" to config.experimentId,
            "titration_type" to config.titrationType,
            "sample_name" to config.sampleName,
            "sample_concentration_M" to format(config.sampleConcentrationM),
            "sample_volume_ml" to format(config.sampleVolumeMl),
            "sample_valence" to format(config.sampleValence),
            "titrant_name" to config.titrantName,
            "titrant_concentration_M" to format(config.titrantConcentrationM),
            "titrant_valence" to format(config.titrantValence),
            "equivalence_formula" to config.equivalenceFormula,
            "calculated_theoretical_equivalence_volume_ml" to format(config.calculatedTheoreticalEquivalenceVolumeMl),
            "sample_concentration_from_theoretical_equivalence_M" to format(config.sampleConcentrationFromTheoreticalEquivalenceM),
            "theoretical_equivalence_volume_ml" to format(config.theoreticalEquivalenceVolumeMl),
            "reference_equivalence_volume_ml" to "",
            "predicted_equivalence_volume_ml" to "",
            "sample_concentration_from_predicted_equivalence_M" to "",
            "predicted_sample_concentration_error_percent" to "",
            "pump_mode" to "phone_local_timeline",
            "pump_state" to pumpState,
            "pump_run_rate_ml_per_s" to format(pumpRateMlPerS),
            "pump_step_count" to formatOptionalLong(pumpStepCount),
            "pump_confirmed_step_count" to formatOptionalLong(pumpConfirmedStepCount),
            "pump_firmware_volume_ml" to formatOptional(pumpFirmwareVolumeMl),
            "pump_last_status" to pumpLastStatusLine,
            "time_s" to format(timeS),
            "frame_id" to frameId.toString(),
            "thermal_time_s" to formatOptional(thermalTimeS),
            "visible_time_s" to formatOptional(visibleTimeS),
            "sync_offset_ms" to formatOptional(syncOffsetMs),
            "sync_quality" to syncQuality,
            "injected_volume_ml" to format(injectedVolumeMl),
            "distance_to_equivalence_ml" to formatOptional(distanceToEquivalenceMl),
            "visible_R_mean" to formatOptional(visibleRMean),
            "visible_G_mean" to formatOptional(visibleGMean),
            "visible_B_mean" to formatOptional(visibleBMean),
            "visible_H_mean" to formatOptional(visibleHMean),
            "visible_S_mean" to formatOptional(visibleSMean),
            "visible_V_mean" to formatOptional(visibleVMean),
            "visible_HSV_delta" to formatOptional(visibleHsvDelta),
            "visible_color_delta" to formatOptional(visibleColorDelta),
            "roi_shape" to roiShape,
            "visible_roi_shape" to visibleRoiShape,
            "thermal_roi_shape" to thermalRoiShape,
            "visible_mask_source" to visibleMaskSource,
            "thermal_mask_source" to thermalMaskSource,
            "visible_mask_area_px" to formatOptionalInt(visibleMaskAreaPx),
            "visible_mask_confidence" to formatOptional(visibleMaskConfidence),
            "visible_mask_bbox" to visibleMaskBbox,
            "visible_mask_component_count" to formatOptionalInt(visibleMaskComponentCount),
            "visible_mask_stability" to visibleMaskStability,
            "thermal_mask_area_px" to formatOptionalInt(thermalMaskAreaPx),
            "thermal_mask_confidence" to formatOptional(thermalMaskConfidence),
            "thermal_mask_bbox" to thermalMaskBbox,
            "thermal_mask_component_count" to formatOptionalInt(thermalMaskComponentCount),
            "thermal_mask_stability" to thermalMaskStability,
            "mask_bbox" to maskBbox,
            "mask_confidence" to formatOptional(maskConfidence),
            "mask_component_count" to formatOptionalInt(maskComponentCount),
            "mask_stability" to maskStability,
            "auto_roi_worker_enabled" to autoRoiWorkerEnabled.toString(),
            "auto_roi_result_status" to autoRoiResultStatus,
            "auto_roi_result_reason" to autoRoiResultReason,
            "auto_roi_dropped_pending" to autoRoiDroppedPending.toString(),
            "thermal_source" to thermalConversionModel,
            "thermal_roi_avg" to "",
            "thermal_roi_max" to "",
            "thermal_roi_min" to "",
            "thermal_matrix_avg" to "",
            "thermal_conversion_model" to thermalConversionModel,
            "thermal_calibrated" to thermalCalibrated.toString(),
            "thermal_matrix_shape" to thermalMatrixShape,
            "thermal_raw_roi_avg" to formatOptional(thermalRawRoiAvg),
            "thermal_raw_roi_min" to formatOptional(thermalRawRoiMin),
            "thermal_raw_roi_max" to formatOptional(thermalRawRoiMax),
            "thermal_raw_mean" to formatOptional(thermalRawMean),
            "thermal_raw_min" to formatOptional(thermalRawMin),
            "thermal_raw_max" to formatOptional(thermalRawMax),
            "thermal_raw_roi_std" to formatOptional(thermalRawRoiStd),
            "thermal_raw_roi_delta" to formatOptional(thermalRawRoiDelta),
            "thermal_raw_roi_p50" to formatOptional(thermalRawRoiP50),
            "thermal_raw_roi_iqr" to formatOptional(thermalRawRoiIqr),
            "thermal_raw_std" to formatOptional(thermalRawStd),
            "csv_session_id" to csvSessionId,
            "csv_row_index" to formatOptionalInt(csvRowIndex),
            "csv_recording_started_epoch_s" to formatOptional(csvRecordingStartedEpochS),
            "csv_recording_elapsed_s" to formatOptional(csvRecordingElapsedS),
            "pump_elapsed_s" to formatOptional(pumpElapsedS),
            "theoretical_equivalence_time_s" to formatOptional(theoreticalEquivalenceTimeS),
            "time_to_equivalence_s" to formatOptional(timeToEquivalenceS),
            "equivalence_window_ml" to formatOptional(equivalenceWindowMl),
            "equivalence_window_label" to equivalenceWindowLabel,
            "sample_concentration_from_injected_M" to formatOptional(sampleConcentrationFromInjectedM),
            "sample_concentration_error_percent" to formatOptional(sampleConcentrationErrorPercent),
            "pending_auto_candidate_requests" to pendingAutoCandidateRequests.toString(),
            "pending_auto_candidate_target" to pendingAutoCandidateTarget,
            "warnings" to warnings,
        )
    }

    private fun formatOptional(value: Double?): String = value?.let { format(it) } ?: ""

    private fun formatOptionalLong(value: Long?): String = value?.toString() ?: ""

    private fun formatOptionalInt(value: Int?): String = value?.toString() ?: ""

    private fun format(value: Double): String = String.format(Locale.US, "%.6f", value)
}
